#!/usr/bin/env node
/* tools/gen_exptexts.js — Owner: core.
 * Generates shared/core/18-exptexts-data.js:
 *   OGX.messages._expTexts   (OgameX) from fixtures/messages-expedition-texts.json: the expedition body texts per locale and key
 *                            (resources/lang/{locale}/t_messages.php) plus the outcome per key;
 *   OGX.messages._gzTexts    (GALAXYZ) from specs/galaxyz/fixtures/messages-texts.json: { en|ru: { expedition: { sys_expe_*: { outcome, text } } } }
 *                            (upstream 2Moons language/{en,ru}/FLEET.php; the fork may have edited them: [UPSTREAM], not seen live).
 * Usage: node tools/gen_exptexts.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const OGX = path.resolve(__dirname, '..');
const SRC = path.join(OGX, 'fixtures/messages-expedition-texts.json');
const GZ_SRC = path.join(OGX, 'specs/galaxyz/fixtures/messages-texts.json');
const OUT = path.join(OGX, 'shared/core/18-exptexts-data.js');

const j = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const data = { outcomeByKey: j.outcome_by_key, texts: {} };
let n = 0;
for (const [loc, keys] of Object.entries(j.texts)) {
  data.texts[loc] = {};
  for (const [key, vars] of Object.entries(keys)) {
    data.texts[loc][key] = vars;
    if (!key.startsWith('_')) n += Object.keys(vars).length;
  }
}
const gzSrc = JSON.parse(fs.readFileSync(GZ_SRC, 'utf8'));
const gz = {};
let gzN = 0;
for (const loc of ['en', 'ru']) {
  if (!gzSrc[loc] || !gzSrc[loc].expedition) continue;
  gz[loc] = { expedition: gzSrc[loc].expedition };
  gzN += Object.keys(gzSrc[loc].expedition).length;
}
const out = `/* shared/core/18-exptexts-data.js — GENERATED by tools/gen_exptexts.js from fixtures/messages-expedition-texts.json (OgameX)
 * and specs/galaxyz/fixtures/messages-texts.json (GALAXYZ, [UPSTREAM] 2Moons texts). Do not edit by hand. Owner: core.
 * OgameX: ${n} expedition body variations in ${Object.keys(data.texts).length} locales. GALAXYZ: ${gzN} expedition texts (${Object.keys(gz).join(', ')}). */
(function (OGX) {
  'use strict';
  const messages = (OGX.messages = OGX.messages || {});
  messages._expTexts = ${JSON.stringify(data)};
  messages._gzTexts = ${JSON.stringify(gz)};
})(window.OGX);
`;
fs.writeFileSync(OUT, out);
console.log('wrote', path.relative(OGX, OUT), n, 'OgameX variations,', gzN, 'GALAXYZ texts');
