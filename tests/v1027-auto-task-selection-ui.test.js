'use strict';
const fs = require('fs'), vm = require('vm'), assert = require('assert');
const source = fs.readFileSync(require('path').join(__dirname, '../popup.js'), 'utf8');
let cfg = { autoTasks: ['tvt'] }, patches = [];
const context = { console, Set, Date, Object, Promise, formChar: 'Hero', settingsSerial: 0, DEF: {}, chrome: { storage: { local: { get: async () => ({ cfg: JSON.parse(JSON.stringify(cfg)) }) } } }, menuPatch: async (rt, extra) => { patches.push({ rt, extra }); cfg = { ...cfg, ...extra.cfgPatch }; }, load: async () => {} };
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('const AUTO_TASK_LABELS'), source.indexOf('const MODE_NAME')) + '\nthis.api={selectedAutoTasks,autoTaskPatch,currentMode,editAutoTask};', context);
const { selectedAutoTasks, autoTaskPatch, currentMode, editAutoTask } = context.api;
const plain = x => JSON.parse(JSON.stringify(x));
assert.deepStrictEqual(plain(selectedAutoTasks({ autoTasks: ['tvt'], campaign: true, fishMode: true })), ['tvt']);
assert.deepStrictEqual(plain(selectedAutoTasks({ autoTasks: [] })), []);
assert.deepStrictEqual(plain(selectedAutoTasks({ autoTasks: ['unknown', 'raid'] })), ['raid']);
assert.deepStrictEqual(plain(autoTaskPatch({ autoTasks: ['tvt'] }, 'fish', true)), { autoTasks: ['tvt', 'fish'] });
assert.deepStrictEqual(plain(autoTaskPatch({ autoTasks: ['tvt', 'fish'] }, 'fish', false)), { autoTasks: ['tvt'] });
assert.deepStrictEqual(plain(autoTaskPatch({ autoTasks: [] }, 'quests', true)), { autoTasks: ['quests'], campaign: true, storyTurnIn: true });
assert.deepStrictEqual(plain(autoTaskPatch({ autoTasks: [] }, 'mammon', true)), { autoTasks: ['mammon'] });
assert.deepStrictEqual(plain(autoTaskPatch({ autoTasks: [] }, 'resources', true)), { autoTasks: ['resources'] });
assert.strictEqual(currentMode({ autoTasks: ['tvt'], fishMode: true }), 'tasks');
assert.strictEqual(currentMode({ autoTasks: ['farm', 'fish', 'raid'] }), 'rb');
assert.strictEqual(currentMode({ autoTasks: ['fish', 'quests'] }), 'quests');
assert.strictEqual(currentMode({ autoTasks: ['raid', 'enchant'] }), 'enchant');
assert.strictEqual(currentMode({ autoTasks: null, fishMode: true }), 'fish');
assert.deepStrictEqual(plain(selectedAutoTasks({ tvtOn: true, fishMode: true, taskOnly: false })), ['tvt', 'fish']);
(async () => {
  await Promise.all([editAutoTask('fish', true), editAutoTask('raid', true)]);
  assert.deepStrictEqual(plain(cfg.autoTasks), ['tvt', 'fish', 'raid']);
  assert(patches.every(p => !Object.hasOwn(p.extra, 'on') && p.rt.manualKickAt > 0));
  await editAutoTask('tvt', false); await editAutoTask('fish', false); await editAutoTask('raid', false);
  assert.deepStrictEqual(plain(cfg.autoTasks), []);
  const html = fs.readFileSync(require('path').join(__dirname, '../popup.html'), 'utf8');
  // 27.10: семнадцатая задача — отдельные Rebirth-подземелья; прежний крафт сохранён.
  assert.strictEqual((html.match(/data-auto-task=/g) || []).length, 17);
  console.log('PASS auto-task selection UI: strict allowlist, migration, priorities, serial edits, no implicit start');
})().catch(e => { console.error(e); process.exitCode = 1; });
