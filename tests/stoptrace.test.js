'use strict';
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..'),content=fs.readFileSync(path.join(root,'content.js'),'utf8');
const bg=fs.readFileSync(path.join(root,'background.js'),'utf8'),pop=fs.readFileSync(path.join(root,'popup.js'),'utf8');
const start=content.indexOf('const netOutage = '),end=content.indexOf('let pageLeaving',start);
assert(start>0&&end>start,'Network outage controller not found');
const events=[]; const ctx=vm.createContext({Date,Set,rec:(...x)=>events.push(x)});
vm.runInContext(content.slice(start,end),ctx);
const call=(path,status,ms)=>vm.runInContext(`observeGameHttp(${JSON.stringify(path)},${status},${ms})`,ctx);
const state=()=>vm.runInContext('({ since: netOutage.since, last: netOutage.last })',ctx);
call('/game/battle/action',502,1000);call('/game/battle/action',502,2000);
assert.equal(state().since,0,'Do not identify global outage from one failing endpoint');
call('/game/battle/sync',502,3000);assert.equal(state().since,3000);
call('/game/battle/sync',200,5000);assert.equal(state().since,3000,'One healthy endpoint is insufficient');
call('/game/time',200,6000);assert.equal(state().since,0,'Two healthy endpoints restore availability');
assert.equal(events.filter(e=>e[1]==='сервер').length,2);
call('/other/api',502,7000);assert.equal(state().since,0,'Ignore unrelated endpoint');
assert(content.includes("const stopMeta = ch.stopMeta?.newValue"),'Stop source must be shown in game log');
for(const [file,code,label] of [[pop,pop,'popup'],[bg,bg,'background'],[content,content,'content']]) assert(file.includes('stopMeta:'),`${label}: stop source not persisted`);
assert(content.includes('location.reload();   // сохраняем URL боя'),'Recovery must not drop current battle URL');
console.log('PASS stoptrace: global 5xx detection, endpoint quorum, recovery and atomic stop attribution');
